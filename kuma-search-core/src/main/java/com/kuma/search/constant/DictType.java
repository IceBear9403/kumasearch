package com.kuma.search.constant;

import lombok.Getter;

/**
 * 词典类型：区分同一张词典表里词条的不同用途。
 *
 * <p>各类词在链路上作用不同——主词扩展领域词、停用词做过滤、同义词做召回扩写，
 * 用类型字段区分复用一张表，便于统一维护与按类型重建分析器。
 *
 * <p>{@link #SENSITIVE} 与前三种<b>不属于同一条链路</b>：它作用在采集入库之前
 * （{@code SensitiveWordFilter} 的 Aho-Corasick 匹配），而不是检索时的分词。
 * 之所以仍然放进这张表，是因为「词库只有一处维护入口」这个好处是实打实的：
 * 另起一张结构完全相同的表，只会让「要加一个词该去哪儿改」多一个答案。
 * 把它和前三者放在一起的代价，仅仅是这个枚举里多了一个成员。
 */
@Getter
public enum DictType {

    /** 主词：为自定义分词补充领域专有词。 */
    MAIN("主词"),

    /** 停用词：过滤无区分度的噪声词，降低误召回。 */
    STOP("停用词"),

    /** 同义词：把不同说法互相扩写，提升召回率。 */
    SYNONYM("同义词"),

    /**
     * 敏感词：采集内容的入库前过滤。
     *
     * <p><b>它只能挡住词库里已有的内容</b> —— 同音字、拆字、拼音、图片文字、
     * 以及任何不含库里字词的表达，一个都挡不住。因此它是第一道闸而不是唯一一道，
     * 人工审核队列与举报入口是必需的补充。不要把它当成「内容安全已实现」。
     *
     * <p>词库需要持续维护（谁维护、多久更新一次见 {@code docs/08-roadmap.md}），
     * 而维护的质量直接决定这道闸的有效性。
     */
    SENSITIVE("敏感词");

    /** 中文描述。 */
    private final String description;

    DictType(String description) {
        this.description = description;
    }
}
